#!/usr/bin/env python3
"""Kazuma Etapa 90: offline, fail-closed ELF symbol provider inventory.

Read textual output of llvm-nm/nm (prefer raw mangled symbols, no '-C'):
  llvm-nm --undefined-only -g combined_aot_loader.o > need.nm
  llvm-nm --defined-only -g runtime_or_lib.o > runtime.nm
  python3 tools/etapa90/symbol_providers.py --undefined need.nm \
      --defined runtime=runtime.nm --json report.json --fail-on-missing

The tool does not perform a link, load code, access networks, or publish any
private artifact. Candidate providers do not prove ABI or a final PS4 link.
"""
from __future__ import annotations

import argparse
from collections import defaultdict
import json
from pathlib import Path
import re
from typing import Iterable

NM_PATTERN = re.compile(r"^\s*(?:(?:[0-9a-fA-F]+|[-]+)\s+)?(?P<kind>[A-Za-z?])\s+(?P<symbol>\S.*?)\s*$")
MATH_SYMBOLS = frozenset(("ceil", "floor", "fma", "trunc"))
DEFINED_GLOBAL = frozenset("ABCDGIRSTVW")
WEAK_GLOBAL = frozenset("VW")


def parse_nm(content: str, *, undefined: bool) -> set[str]:
    """Read raw or demangled nm text; ignore object labels and local symbols.

    Keep references by exact spelling, including ELF symbol versions.
    """
    result: set[str] = set()
    for raw in content.splitlines():
        line = raw.strip()
        if not line or line.endswith(":"):
            continue
        match = NM_PATTERN.match(line)
        if match is None:
            raise ValueError(f"Invalid nm record: {line[:100]!r}")
        kind = match.group("kind")
        symbol = match.group("symbol")
        if undefined:
            if kind.upper() == "U":
                result.add(symbol)
        elif kind in DEFINED_GLOBAL:
            result.add(symbol)
        elif kind in WEAK_GLOBAL:
            result.add(symbol)
    return result


def category(symbol: str) -> str:
    """Report approximate categories only; provider matches remain exact."""
    # Heuristics are for triage, never to claim resolution.
    if symbol in MATH_SYMBOLS:
        return "libm"
    if symbol.startswith(("nx::", "_ZN2nx", "_ZN3nx")):
        return "nx_runtime"
    if symbol.startswith(("plat::", "_ZN4plat")):
        return "platform"
    if symbol.startswith(("_Z", "__cxa_", "__gxx_", "_Unwind_", "std::")):
        return "cxx_abi"
    return "c_or_other"


def analyze(undefined_symbols: Iterable[str],
            providers: dict[str, set[str]]) -> dict:
    needs = sorted(set(undefined_symbols))
    by_name: dict[str, list[str]] = defaultdict(list)
    for provider, symbols in sorted(providers.items()):
        for name in symbols:
            by_name[name].append(provider)

    rows = []
    for name in needs:
        candidates = by_name.get(name, [])
        rows.append({
            "symbol": name,
            "category": category(name),
            "candidate_providers": candidates,
            # Note: "matched" means a declaration/definition exists by exact
            # name, not that a strict linker or ABI accepted the provider.
            "status": "candidate" if candidates else "missing"
        })
    return {
        "required": len(rows),
        "candidate_matched": sum(x["status"] == "candidate" for x in rows),
        "missing": sum(x["status"] == "missing" for x in rows),
        "strict_link_verified": False,
        "ps4_eboot_produced": False,
        "symbols": rows
    }


def parse_provider(value: str) -> tuple[str, Path]:
    label, sep, file = value.partition("=")
    if not sep or not label or not file:
        raise ValueError("A provider must be LABEL=FILE, e.g. loader=loader.nm")
    return label, Path(file)


def main() -> int:
    parser = argparse.ArgumentParser(description="Offline undefined-symbol provider audit")
    parser.add_argument("--undefined", required=True, type=Path,
                        help="Text file generated by nm -u -g on the private combined object")
    parser.add_argument("--defined", action="append", default=[],
                        metavar="LABEL=FILE", help="nm --defined-only -g provider listing")
    parser.add_argument("--json", type=Path, help="Optional private JSON output")
    parser.add_argument("--fail-on-missing", action="store_true",
                        help="Exit 2 when any required symbol has no candidate provider")
    args = parser.parse_args()

    try:
        needs = parse_nm(args.undefined.read_text(encoding="utf-8"), undefined=True)
        providers: dict[str, set[str]] = {}
        for value in args.defined:
            label, file = parse_provider(value)
            if label in providers:
                raise ValueError("Duplicate provider label")
            providers[label] = parse_nm(file.read_text(encoding="utf-8"), undefined=False)
        result = analyze(needs, providers)
    except (OSError, ValueError) as error:
        parser.error(str(error))

    report = json.dumps(result, indent=2, ensure_ascii=False) + "\n"
    if args.json:
        args.json.write_text(report, encoding="utf-8")
    print(f"required={result['required']} matched={result['candidate_matched']} "
          f"missing={result['missing']} strict_link_verified=NO")
    for row in result["symbols"]:
        if row["status"] == "missing":
            print(f"  MISSING [{row['category']}] {row['symbol']}")
    return 2 if args.fail_on_missing and result["missing"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
